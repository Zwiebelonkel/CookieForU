import express, { type Request, type Response, type NextFunction } from 'express';
import type { Client } from '@libsql/client';
import { fileURLToPath } from 'node:url';
import { HEX_ID, describe, findCookie, issueCookie, takeBite } from './cookies.js';
import { certificatePage, notFoundPage } from './pages.js';

interface Config { publicBaseUrl: string; corsOrigin?: string; rateLimits?: boolean }

export function createApp(db: Client, config: Config) {
  const app = express();
  const origin = new URL(config.publicBaseUrl).origin;
  app.disable('x-powered-by');
  // Render is the public-facing reverse proxy for the single web service.
  app.set('trust proxy', 1);

  app.use((req, res, next) => {
    res.set({
      'X-Content-Type-Options': 'nosniff',
      'Referrer-Policy': 'no-referrer',
      'Content-Security-Policy': "default-src 'none'; script-src 'self'; style-src 'self'; img-src 'self' data:; connect-src 'self'; base-uri 'none'; frame-ancestors 'none'; form-action 'none'"
    });
    if (req.path.startsWith('/api/') || req.path.startsWith('/verify/')) {
      res.set('Cache-Control', 'no-store');
    }
    next();
  });

  app.use('/api', (req, res, next) => {
    const requestOrigin = req.get('origin');
    if (requestOrigin && requestOrigin !== origin && requestOrigin !== config.corsOrigin) {
      res.status(403).json({ error: 'Origin not allowed' }); return;
    }
    if (requestOrigin) {
      res.set('Access-Control-Allow-Origin', requestOrigin);
      res.vary('Origin');
    }
    if (req.method === 'OPTIONS') {
      res.set('Access-Control-Allow-Methods', 'GET, POST, OPTIONS');
      res.set('Access-Control-Allow-Headers', 'Content-Type, Authorization');
      res.sendStatus(204); return;
    }
    next();
  });

  // A small per-instance throttle; shared/distributed limits can be added later.
  const buckets = new Map<string, { count: number; expires: number }>();
  app.use('/api', (req, res, next) => {
    if (config.rateLimits === false) { next(); return; }
    const now = Date.now();
    for (const [key, bucket] of buckets) if (bucket.expires <= now) buckets.delete(key);
    const issuing = req.method === 'POST' && req.path === '/cookies';
    const key = `${req.ip}:${issuing ? 'issue' : 'other'}`;
    const bucket = buckets.get(key) ?? { count: 0, expires: now + 60_000 };
    bucket.count++;
    buckets.set(key, bucket);
    if (bucket.count > (issuing ? 20 : 240)) {
      res.set('Retry-After', String(Math.ceil((bucket.expires - now) / 1000)));
      res.status(429).json({ error: 'A little patience. Please try again shortly.' }); return;
    }
    next();
  });

  app.use(express.json({ limit: '4kb', strict: true }));

  app.get('/health', async (_req, res) => {
    try { await db.execute('SELECT 1'); res.json({ ok: true }); }
    catch { res.status(503).json({ ok: false }); }
  });

  app.post('/api/cookies', async (req, res) => {
    const body = req.body;
    if (!body || typeof body.ownerToken !== 'string' || !HEX_ID.test(body.ownerToken) ||
        Object.keys(body).some(key => key !== 'ownerToken')) {
      res.status(400).json({ error: 'Send only a random 64-character ownerToken. IDs and rarities are generated by the server.' }); return;
    }
    const { row, created } = await issueCookie(db, body.ownerToken);
    res.status(created ? 201 : 200).json({ cookie: describe(row, origin) });
  });

  app.get('/api/cookies/:id', async (req, res) => {
    const id = String(req.params.id);
    if (!HEX_ID.test(id)) { res.status(400).json({ error: 'Invalid cookie ID' }); return; }
    const row = await findCookie(db, id);
    if (!row) { res.status(404).json({ error: 'This cookie was not issued by this server.' }); return; }
    res.json({ cookie: describe(row, origin) });
  });

  app.post('/api/cookies/:id/bite', async (req, res) => {
    const id = String(req.params.id);
    const authorization = req.get('authorization') ?? '';
    const match = /^Bearer ([0-9a-f]{64})$/.exec(authorization);
    const expectedBites = req.body?.expectedBites;
    if (!HEX_ID.test(id) || !Number.isInteger(expectedBites) || expectedBites < 0 || expectedBites > 2 ||
        Object.keys(req.body ?? {}).some(key => key !== 'expectedBites')) {
      res.status(400).json({ error: 'Invalid cookie ID or expectedBites (0, 1 or 2 required)' }); return;
    }
    if (!match) { res.status(401).json({ error: 'An owner token is required to eat this cookie.' }); return; }
    const row = await takeBite(db, id, match[1], expectedBites);
    if (!row) {
      // No owner token or owner hash ever appears in public responses.
      res.status(409).json({ error: 'Bite not applied. Refresh the cookie; it may have changed, been eaten, or belong to someone else.' }); return;
    }
    res.json({ cookie: describe(row, origin) });
  });

  app.get(['/verify/:id', '/api/cookies/:id/certificate'], async (req, res) => {
    const id = String(req.params.id);
    if (!HEX_ID.test(id)) { res.status(404).type('html').send(notFoundPage()); return; }
    const row = await findCookie(db, id);
    if (!row) { res.status(404).type('html').send(notFoundPage()); return; }
    res.type('html').send(await certificatePage(describe(row, origin), req.path.endsWith('/certificate')));
  });

  app.use(express.static(fileURLToPath(new URL('../public/', import.meta.url)), { maxAge: 0 }));
  app.use((_req, res) => res.status(404).json({ error: 'Not found' }));
  app.use((error: unknown, _req: Request, res: Response, _next: NextFunction) => {
    const status = typeof error === 'object' && error !== null && 'status' in error ? Number(error.status) : 500;
    if (status === 400 || status === 413) {
      res.status(status).json({ error: status === 413 ? 'Request too large' : 'Invalid JSON' }); return;
    }
    // Do not log request headers, owner tokens, database tokens or database URLs.
    console.error('Cookie service request failed.');
    res.status(503).json({ error: 'The cookie service is temporarily unavailable. Please try again.' });
  });
  return app;
}
